const router=require('express').Router();
const site=require('../controllers/siteController');
const contact=require('../controllers/contactController');
const appointments=require('../controllers/appointmentController');
const chat=require('../controllers/chatController');
const {rateLimit}=require('express-rate-limit');
const writeLimit=rateLimit({windowMs:15*60*1000,limit:35,standardHeaders:'draft-8',legacyHeaders:false,message:{ok:false,message:'Demasiadas solicitudes. Vuelve a intentarlo en unos minutos.'}});
const chatLimit=rateLimit({windowMs:60*1000,limit:12,standardHeaders:'draft-8',legacyHeaders:false,message:{ok:false,message:'Has enviado muchos mensajes. Inténtalo de nuevo pronto.'}});
router.get('/site',site.home);
router.get('/services',site.services);
router.get('/specialties',site.specialties);
router.get('/prices',site.prices);
router.get('/about',site.about);
router.get('/gallery',site.gallery);
router.get('/faqs',site.faqs);
router.post('/contact',writeLimit,contact.create);
router.post('/appointments',writeLimit,appointments.create);
router.get('/chat/health',chat.health);
router.post('/chat',chatLimit,chat.ask);
module.exports=router;
